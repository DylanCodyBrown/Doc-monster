use anyhow::{Context, Result};
use quick_xml::{Reader, events::Event};
use std::io::{Cursor, Read};

pub fn convert(bytes: &[u8], fallback: &str) -> Result<super::Out> {
    let mut zip = zip::ZipArchive::new(Cursor::new(bytes)).context("not a valid DOCX archive")?;
    let mut xml = String::new();
    zip.by_name("word/document.xml")
        .context("DOCX is missing word/document.xml")?
        .read_to_string(&mut xml)?;
    let (mut md, stats) = parse(&xml)?;
    let read = |zip: &mut zip::ZipArchive<Cursor<&[u8]>>, name: &str| -> Option<String> {
        let mut s = String::new();
        zip.by_name(name).ok()?.read_to_string(&mut s).ok()?;
        Some(s)
    };
    // Footnotes, endnotes and comments live in their own parts; bring their text along.
    for (part, heading) in [
        ("word/footnotes.xml", "Footnotes"),
        ("word/endnotes.xml", "Endnotes"),
        ("word/comments.xml", "Comments"),
    ] {
        if let Some(x) = read(&mut zip, part) {
            let (notes, _) = parse(&x)?;
            let items: Vec<String> = notes
                .split("\n\n")
                .map(str::trim)
                .filter(|n| !n.is_empty())
                .map(|n| format!("- {n}"))
                .collect();
            if !items.is_empty() {
                md.push_str(&format!("\n## {heading}\n\n{}\n", items.join("\n")));
            }
        }
    }
    let names: Vec<String> = zip
        .file_names()
        .filter_map(|n| n.ok().map(|n| n.to_string()))
        .collect();
    let mut omitted = Vec::new();
    // Page headers and footers: kept once each (they repeat on every page).
    let mut seen = std::collections::HashSet::new();
    let mut furniture = Vec::new();
    for n in names.iter().filter(|n| {
        (n.starts_with("word/header") || n.starts_with("word/footer")) && n.ends_with(".xml")
    }) {
        if let Some(x) = read(&mut zip, n) {
            let (text, _) = parse(&x)?;
            for line in text
                .lines()
                .map(str::trim)
                .filter(|l| l.chars().any(char::is_alphanumeric))
            {
                if seen.insert(line.to_string()) {
                    furniture.push(format!("- {}", line.trim_start_matches("- ")));
                }
            }
        }
    }
    if !furniture.is_empty() {
        md.push_str(&format!(
            "\n## Page headers and footers\n\n{}\n",
            furniture.join("\n")
        ));
    }
    let images = names
        .iter()
        .filter(|n| n.starts_with("word/media/"))
        .count();
    if images > 0 {
        omitted.push(format!(
            "{images} image{}",
            if images == 1 { "" } else { "s" }
        ));
    }
    if stats.deletions > 0 {
        omitted.push(format!(
            "{} tracked deletion{} (the accepted text is shown)",
            stats.deletions,
            if stats.deletions == 1 { "" } else { "s" }
        ));
    }
    let mut core = String::new();
    if let Ok(mut f) = zip.by_name("docProps/core.xml") {
        let _ = f.read_to_string(&mut core);
    }
    let title = super::xml_field(&core, "title")
        .or_else(|| super::first_heading(&md))
        .unwrap_or_else(|| fallback.to_string());
    let description = super::xml_field(&core, "subject")
        .or_else(|| super::xml_field(&core, "description"))
        .filter(|d| !d.to_lowercase().starts_with("generated by"));
    let mut out = super::Out::new(title, md).with_description(description);
    out.omitted = omitted;
    Ok(out)
}

#[derive(Default)]
struct Para {
    text: String,
    heading: Option<usize>,
    list: bool,
}

#[derive(Default)]
struct Stats {
    deletions: usize,
}

#[cfg(test)]
fn document_xml_to_markdown(xml: &str) -> Result<String> {
    parse(xml).map(|(md, _)| md)
}

fn parse(xml: &str) -> Result<(String, Stats)> {
    let mut stats = Stats::default();
    // Inside a copy we must not read twice: legacy fallbacks of text boxes, moved-from text.
    let mut skip = 0usize;
    let mut span = 1usize;
    let mut reader = Reader::from_str(xml);
    let mut out = String::new();
    let mut para = Para::default();
    let mut in_text = false;
    // Table state: rows of cells; `None` when not inside a table.
    let mut table: Option<Vec<Vec<String>>> = None;
    let mut cell = String::new();

    loop {
        match reader.read_event()? {
            Event::Start(e)
                if skip > 0 || matches!(e.local_name().as_ref(), "Fallback" | "moveFrom") =>
            {
                skip += 1
            }
            Event::End(_) if skip > 0 => skip -= 1,
            _ if skip > 0 => {}
            Event::Start(e) | Event::Empty(e) => match e.local_name().as_ref() {
                "del" => stats.deletions += 1,
                "gridSpan" => {
                    span = e
                        .attributes()
                        .flatten()
                        .find(|a| a.key.local_name().as_ref() == "val")
                        .and_then(|a| a.value.parse().ok())
                        .unwrap_or(1usize)
                        .clamp(1, 64);
                }
                "p" => para = Para::default(),
                "t" => in_text = true,
                "tab" => para.text.push('\t'),
                "br" => para.text.push(' '),
                "numPr" => para.list = true,
                "pStyle" => {
                    for a in e.attributes().flatten() {
                        if a.key.local_name().as_ref() == "val" {
                            let v = a.value.to_ascii_lowercase();
                            para.heading = if v == "title" {
                                Some(1)
                            } else {
                                v.strip_prefix("heading")
                                    .and_then(|n| n.trim().parse::<usize>().ok())
                                    .map(|n| n.clamp(1, 6))
                            };
                            if v.contains("list") {
                                para.list = true;
                            }
                        }
                    }
                }
                "tbl" => table = Some(Vec::new()),
                "tr" => {
                    if let Some(t) = table.as_mut() {
                        t.push(Vec::new());
                    }
                }
                _ => {}
            },
            Event::Text(t) if in_text => para.text.push_str(&t),
            Event::GeneralRef(r) if in_text => {
                if let Some(c) = r.resolve_char_ref()? {
                    para.text.push(c);
                } else {
                    match &*r {
                        "amp" => para.text.push('&'),
                        "lt" => para.text.push('<'),
                        "gt" => para.text.push('>'),
                        "quot" => para.text.push('"'),
                        "apos" => para.text.push('\''),
                        _ => {}
                    }
                }
            }
            Event::End(e) => match e.local_name().as_ref() {
                "t" => in_text = false,
                "p" => {
                    let text = para.text.trim();
                    if table.is_some() {
                        if !cell.is_empty() && !text.is_empty() {
                            cell.push(' ');
                        }
                        cell.push_str(text);
                    } else if !text.is_empty() {
                        match (para.heading, para.list) {
                            (Some(n), _) => out.push_str(&format!("{} {text}\n\n", "#".repeat(n))),
                            (None, true) => out.push_str(&format!("- {text}\n")),
                            _ => out.push_str(&format!("{text}\n\n")),
                        }
                    }
                    para = Para::default();
                }
                "tc" => {
                    if let Some(row) = table.as_mut().and_then(|t| t.last_mut()) {
                        row.push(cell.replace('|', "\\|"));
                        // A cell merged across columns keeps the next cells in their columns.
                        row.extend(std::iter::repeat_n(String::new(), span - 1));
                    }
                    span = 1;
                    cell.clear();
                }
                "tbl" => {
                    if let Some(rows) = table.take() {
                        out.push_str(&render_table(&rows));
                        out.push('\n');
                    }
                }
                _ => {}
            },
            Event::Eof => break,
            _ => {}
        }
    }
    Ok((tidy_lists(&out), stats))
}

/// Lists emit "- item\n" without a trailing blank line; make sure the block
/// after a list is separated by one so Markdown renders it correctly.
fn tidy_lists(md: &str) -> String {
    let mut out = String::new();
    let mut prev_list = false;
    for line in md.lines() {
        let is_list = line.starts_with("- ");
        if prev_list && !is_list && !line.is_empty() {
            out.push('\n');
        }
        out.push_str(line);
        out.push('\n');
        prev_list = is_list;
    }
    out
}

fn render_table(rows: &[Vec<String>]) -> String {
    let width = rows.iter().map(Vec::len).max().unwrap_or(0);
    if width == 0 {
        return String::new();
    }
    let mut out = String::new();
    for (i, row) in rows.iter().enumerate() {
        out.push('|');
        for c in 0..width {
            out.push_str(&format!(
                " {} |",
                row.get(c).map(String::as_str).unwrap_or("")
            ));
        }
        out.push('\n');
        if i == 0 {
            out.push('|');
            out.push_str(&" --- |".repeat(width));
            out.push('\n');
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const W: &str = r#"<w:document xmlns:w="x"><w:body>
<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr><w:r><w:t>Report</w:t></w:r></w:p>
<w:p><w:r><w:t>Fish &amp; chips</w:t></w:r></w:p>
<w:p><w:pPr><w:numPr/></w:pPr><w:r><w:t>one</w:t></w:r></w:p>
<w:p><w:pPr><w:numPr/></w:pPr><w:r><w:t>two</w:t></w:r></w:p>
<w:tbl><w:tr><w:tc><w:p><w:r><w:t>A</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>B</w:t></w:r></w:p></w:tc></w:tr>
<w:tr><w:tc><w:p><w:r><w:t>1</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>2</w:t></w:r></w:p></w:tc></w:tr></w:tbl>
</w:body></w:document>"#;

    #[test]
    fn merged_cells_keep_columns_aligned_and_fallback_copies_are_skipped() {
        let xml = r#"<w:document xmlns:w="x" xmlns:mc="m"><w:body>
<w:tbl><w:tr><w:tc><w:tcPr><w:gridSpan w:val="2"/></w:tcPr><w:p><w:r><w:t>Wide</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>C</w:t></w:r></w:p></w:tc></w:tr>
<w:tr><w:tc><w:p><w:r><w:t>1</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>2</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>3</w:t></w:r></w:p></w:tc></w:tr></w:tbl>
<w:p><mc:AlternateContent><mc:Choice><w:r><w:t>Box text</w:t></w:r></mc:Choice><mc:Fallback><w:r><w:t>Box text</w:t></w:r></mc:Fallback></mc:AlternateContent></w:p>
<w:p><w:del><w:r><w:delText>gone</w:delText></w:r></w:del><w:r><w:t>kept</w:t></w:r></w:p>
</w:body></w:document>"#;
        let (md, stats) = parse(xml).unwrap();
        assert!(
            md.contains("| Wide |  | C |\n| --- | --- | --- |\n| 1 | 2 | 3 |"),
            "{md}"
        );
        assert_eq!(md.matches("Box text").count(), 1, "{md}");
        assert!(md.contains("kept") && !md.contains("gone"));
        assert_eq!(stats.deletions, 1);
    }

    #[test]
    fn converts_headings_entities_lists_tables() {
        let md = document_xml_to_markdown(W).unwrap();
        assert!(md.contains("# Report\n"));
        assert!(md.contains("Fish & chips"));
        assert!(md.contains("- one\n- two\n"));
        assert!(md.contains("| A | B |\n| --- | --- |\n| 1 | 2 |"));
    }
}
